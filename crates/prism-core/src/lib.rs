use chrono::{DateTime, Utc};
use serde::Serialize;
use ts_rs::TS;

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct Overview {
    pub demo: bool,
    pub accounts: Vec<AccountSnapshot>,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct AccountSnapshot {
    pub account_id: String,
    pub provider_name: String,
    pub alias: String,
    pub snapshot: QuotaSnapshot,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct QuotaSnapshot {
    pub observed_at: DateTime<Utc>,
    pub source: SourceKind,
    pub windows: Vec<QuotaWindow>,
    pub balances: Vec<Balance>,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum SourceKind {
    Demo,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct QuotaWindow {
    pub window_id: String,
    pub label: String,
    pub unit: Unit,
    pub period: Period,
    pub used: Option<String>,
    pub remaining: Option<String>,
    pub limit: Option<String>,
    pub used_percent: Option<f64>,
    pub remaining_percent: Option<f64>,
    pub reset_at: Option<DateTime<Utc>>,
    pub next_recovery_at: Option<DateTime<Utc>>,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum Unit {
    Request,
    Token,
    Credit,
    Percent,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Period {
    Rolling { seconds: u32 },
    Fixed,
    Unknown,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct Balance {
    pub amount: String,
    pub currency: String,
}

#[derive(Clone, Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct PublicError {
    pub code: String,
    pub message: String,
}

impl std::fmt::Display for PublicError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "{}: {}", self.code, self.message)
    }
}

impl std::error::Error for PublicError {}

pub trait QuotaProvider: Send + Sync {
    fn fetch_overview(&self) -> Result<Overview, PublicError>;
}

pub fn quota_percent(
    amount: Option<u64>,
    limit: Option<u64>,
    reported: Option<f64>,
) -> Result<Option<f64>, PublicError> {
    let invalid = || PublicError {
        code: "invalid_quota".into(),
        message: "Invalid quota values".into(),
    };
    if matches!(limit, Some(0))
        || matches!((amount, limit), (Some(value), Some(max)) if value > max)
    {
        return Err(invalid());
    }
    if let Some(percent) = reported {
        if !percent.is_finite() || !(0.0..=100.0).contains(&percent) {
            return Err(invalid());
        }
        return Ok(Some(percent));
    }
    Ok(match (amount, limit) {
        (Some(amount), Some(limit)) => Some(amount as f64 / limit as f64 * 100.0),
        _ => None,
    })
}

pub fn typescript_definitions() -> String {
    let config = ts_rs::Config::default();
    [
        Overview::decl(&config),
        AccountSnapshot::decl(&config),
        QuotaSnapshot::decl(&config),
        SourceKind::decl(&config),
        QuotaWindow::decl(&config),
        Unit::decl(&config),
        Period::decl(&config),
        Balance::decl(&config),
        PublicError::decl(&config),
    ]
    .into_iter()
    .map(|definition| format!("export {definition}\n"))
    .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_zero_and_invalid_are_distinct() {
        assert_eq!(quota_percent(None, Some(100), None).unwrap(), None);
        assert_eq!(quota_percent(Some(0), Some(100), None).unwrap(), Some(0.0));
        assert_eq!(quota_percent(None, None, Some(68.0)).unwrap(), Some(68.0));
        assert!(quota_percent(Some(1), Some(0), None).is_err());
        assert!(quota_percent(Some(101), Some(100), None).is_err());
        assert!(quota_percent(None, None, Some(f64::NAN)).is_err());
        assert!(quota_percent(None, None, Some(101.0)).is_err());
    }

    #[test]
    fn generated_types_match_contract() {
        let expected = format!(
            "// Generated by cargo run -p prism-core --example export_types. Do not edit.\n{}",
            typescript_definitions()
        );
        assert_eq!(
            include_str!("../../../apps/desktop/src/generated/types.ts"),
            expected
        );
    }
}
